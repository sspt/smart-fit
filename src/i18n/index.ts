export const languages = {
  en: "English",
  es: "Español",
  pt: "Português",
  fr: "Français",
  it: "Italiano",
  pl: "Polski",
  de: "Deutsch",
  nl: "Nederlands",
} as const;
export type Language = keyof typeof languages;

const preferenceKey = "kwest-language";
export function getLanguage(): Language {
  let saved: string | null = null;
  try {
    saved = globalThis.localStorage?.getItem(preferenceKey) ?? null;
  } catch {}
  for (const candidate of [
    saved,
    ...(globalThis.navigator?.languages ?? []),
    globalThis.navigator?.language,
  ]) {
    const code = candidate?.split("-")[0].toLowerCase();
    if (code && Object.hasOwn(languages, code)) return code as Language;
  }
  return "en";
}
export const getActiveLocale = () =>
  getLanguage() === "en" ? "en-GB" : getLanguage();
export function setLanguage(language: Language) {
  localStorage.setItem(preferenceKey, language);
}
export function setDocumentLanguage() {
  if (typeof document !== "undefined")
    document.documentElement.lang = getLanguage();
}

